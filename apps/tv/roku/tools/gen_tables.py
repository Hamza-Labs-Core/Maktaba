"""Writes source/visualtext_tables.brs, the device shaper's data, from the reference (story 58.15).

The tables come from what `visual.py` uses, so the device and the reference cannot drift apart
on data: the shaping table (arabic-reshaper's letters, limited as visual.TABLE says), the
lam-alef ligatures, Python's Unicode bidi classes (Python 3.12: Unicode 15.0), python-bidi's
mirrored glyphs, and the paired brackets (an opening or closing punctuation with a mirrored
glyph, UAX #9 BD14 and BD15).

Each character gets one class code:

    L R A(AL) E(EN) S(ES) T(ET) N(AN) C(CS) M(NSM) W(WS) O(ON)   UAX #9's classes
    B   removed (BN: soft hyphen, ZWSP, BOM...)
    P   becomes a space (tab, CR, LF, the line and paragraph separators)
    H   removed (tashkeel)
    X   keeps the whole string in logical order (visual.unsupported)
    1 2 3   LRM, RLM, ALM: steer the order as L, R, AL, then removed

    gen_tables.py [--check]     # from the repository root, with requirements.txt
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from importlib.metadata import version
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from bidi.mirror import MIRRORED  # noqa: E402

import visual  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "source" / "visualtext_tables.brs"
CLASSES = {
    "L": "L",
    "R": "R",
    "AL": "A",
    "EN": "E",
    "ES": "S",
    "ET": "T",
    "AN": "N",
    "CS": "C",
    "NSM": "M",
    "WS": "W",
    "ON": "O",
    "BN": "B",
    "S": "P",
    "B": "P",
}
MARKS = {0x200E: "1", 0x200F: "2", 0x061C: "3"}


def code(cp: int) -> str:
    ch = chr(cp)
    if 0xD800 <= cp <= 0xDFFF:
        return "O"  # a lone surrogate (brs-engine's strings are UTF-16): neutral, never split
    if cp in MARKS:
        return MARKS[cp]
    if ch in visual._TO_SPACE:
        return "P"
    bc = unicodedata.bidirectional(ch)
    # in visual.normalise's order: gated format characters stay, other BN go, then the gate
    if ch in visual._GATED_FORMAT:
        return "X"
    if bc == "BN":
        return "B"
    if visual.unsupported(ch) is not None:
        return "X"
    if visual.is_harakah(ch):
        return "H"
    if bc in ("LRE", "RLE", "LRO", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"):
        return "X"
    return CLASSES.get(bc, "L")


def ranges() -> list[tuple[int, int, str]]:
    """The non-L runs of planes 0 and 1 outside the two dense blocks (planes 2 and up are L)."""
    out: list[tuple[int, int, str]] = []
    for cp in range(0x0100, 0x20000):
        if 0x0600 <= cp <= 0x06FF:
            continue
        c = code(cp)
        if c == "L":
            continue
        if out and out[-1][1] == cp - 1 and out[-1][2] == c:
            out[-1] = (out[-1][0], cp, c)
        else:
            out.append((cp, cp, c))
    return out


def brackets() -> list[tuple[int, int]]:
    """(opening, closing) pairs: Ps with a mirrored glyph that is Pe."""
    out = []
    for a, b in MIRRORED.items():
        bmp = len(a) == 1 and len(b) == 1 and ord(a) < 0x10000
        if bmp and unicodedata.category(a) == "Ps" and unicodedata.category(b) == "Pe":
            out.append((ord(a), ord(b)))
    return sorted(out)


def _chunks(items: list[str], per: int) -> list[str]:
    return [", ".join(items[i : i + per]) for i in range(0, len(items), per)]


def render() -> str:
    latin = "".join(code(cp) for cp in range(0x100))
    arabic = "".join(code(cp) for cp in range(0x600, 0x700))
    for s in (latin, arabic):
        assert '"' not in s and len(s) == 256
    rs = ranges()
    forms: list[str] = []
    for cp in range(0x600, 0x700):
        f = visual.TABLE.get(chr(cp))
        forms.append("invalid" if f is None else "[" + ", ".join(str(ord(x)) if x else "0" for x in f) + "]")
    lam_alef: list[str] = []
    for name, (letters, lig) in visual._ligatures.LETTERS_LIGATURES:
        if name in visual.LAM_ALEF:
            assert letters[0] == "\u0644" and len(letters) == 2
            lam_alef.append(f'"{ord(letters[1])}": [{ord(lig[0])}, {ord(lig[3])}]')
    mirror = [
        f'"{ord(a)}": {ord(b)}'
        for a, b in sorted(MIRRORED.items())
        if len(a) == 1 and ord(a) < 0x10000 and ord(b) < 0x10000
    ]
    br = brackets()

    lines = [
        "' Generated by apps/tv/roku/tools/gen_tables.py (story 58.15). Do not edit: run it again.",
        f"' arabic-reshaper {version('arabic-reshaper')}, python-bidi {version('python-bidi')},"
        f" Unicode {unicodedata.unidata_version}.",
        "' Class codes: L R A(AL) E(EN) S(ES) T(ET) N(AN) C(CS) M(NSM) W(WS) O(ON); B removed (BN);",
        "' P becomes a space; H removed (tashkeel); X keeps the string logical; 1 2 3 LRM RLM ALM.",
        "",
        "' The class of each character U+0000-U+00FF.",
        "function vt_TableLatin() as String",
        f'    return "{latin}"',
        "end function",
        "",
        "' The class of each character U+0600-U+06FF (X: outside the shaping table).",
        "function vt_TableArabic() as String",
        f'    return "{arabic}"',
        "end function",
        "",
        "' The other characters of planes 0 and 1 that are not L, as runs: starts, ends (inclusive), codes.",
        "function vt_TableRanges() as Object",
        "    starts = [",
    ]
    lines += [f"        {c}" for c in _chunks([str(r[0]) for r in rs], 16)]
    lines += ["    ]", "    ends = ["]
    lines += [f"        {c}" for c in _chunks([str(r[1]) for r in rs], 16)]
    lines += [
        "    ]",
        f'    codes = "{"".join(r[2] for r in rs)}"',
        "    return {starts: starts, ends: ends, codes: codes}",
        "end function",
        "",
    ]
    lines += [
        "' The shaping table, U+0600-U+06FF: invalid, or [isolated, initial, medial, final] (0: none).",
        "function vt_TableForms() as Object",
        "    return [",
    ]
    lines += [f"        {c}" for c in _chunks(forms, 8)]
    lines += ["    ]", "end function", ""]
    lines += [
        "' Lam (U+0644) followed by an alef: the alef's code -> [isolated, final] ligature.",
        "function vt_TableLamAlef() as Object",
        "    return {" + ", ".join(lam_alef) + "}",
        "end function",
        "",
        "' Mirrored glyphs (UAX #9 L4): code -> code, keyed by the decimal code.",
        "function vt_TableMirror() as Object",
        "    return {",
    ]
    lines += [f"        {c}" for c in _chunks(mirror, 8)]
    lines += ["    }", "end function", ""]
    lines += [
        "' Paired brackets (UAX #9 BD16): opening codes and the closing code of each.",
        "function vt_TableBrackets() as Object",
        "    return {open: ["
        + ", ".join(str(a) for a, _ in br)
        + "], close: ["
        + ", ".join(str(b) for _, b in br)
        + "]}",
        "end function",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail when the committed tables are stale")
    args = ap.parse_args(argv)
    want = render()
    if args.check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != want:
            print(f"::error::{OUT.name} is stale: run apps/tv/roku/tools/gen_tables.py", file=sys.stderr)
            return 1
        print(f"{OUT.name}: up to date")
        return 0
    OUT.write_text(want, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
