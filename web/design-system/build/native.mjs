// Native token files (Story 48.2): MaktabaKit's `Tokens.swift` and Android core's
// `Tokens.kt`, generated from the same resolved tokens as the web's CSS.
//
// Both files are committed. `build-tokens.mjs --check` (run by `make test-tokens`,
// which CI runs) fails when either differs from what these emitters produce, so a
// hand edit or a JSON change without a rebuild cannot merge.
//
// What they carry: the semantic colours as light/dark pairs, the brass palette,
// spacing, radii, type sizes and the two font families the apps bundle. Elevation,
// motion and breakpoints stay web-only (each platform has its own).

import { parseColor } from "./colors.mjs";

export const SWIFT_PATH = "apps/apple/MaktabaKit/Sources/MaktabaKit/Tokens.swift";
export const KOTLIN_PATH =
  "apps/android/core/src/main/kotlin/com/hamzalabs/maktaba/core/ui/Tokens.kt";

const HEADER = [
  "Generated by web/design-system/build/build-tokens.mjs from web/design-system/tokens/.",
  "Do not edit by hand: change the JSON and run `make build-tokens`.",
  "`make test-tokens` (run in CI) fails when this file is stale.",
];

/** `accent-fg` → `accentFg`; a leading digit gets `prefix` (`50` → `brand50`). */
export function identifier(key, prefix = "") {
  const camel = String(key).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return /^[0-9]/.test(camel) ? `${prefix}${camel}` : camel;
}

/** "16px" → 16. Anything else is a source error. */
export function px(value) {
  const m = /^(-?\d+(?:\.\d+)?)px$/.exec(String(value));
  if (!m) throw new Error(`expected a px length, got ${JSON.stringify(value)}`);
  return Number(m[1]);
}

/** "Amiri, IBM Plex Sans Arabic, serif" → "Amiri". */
export function firstFamily(value) {
  return String(value)
    .split(",")[0]
    .trim()
    .replace(/^["']|["']$/g, "");
}

const hex2 = (n) => n.toString(16).toUpperCase().padStart(2, "0");
const alpha255 = (a) => Math.round(a * 255);

/** 0xRRGGBBAA, as SwiftUI-side code builds colours from it. */
export function rgbaHex(value) {
  const { r, g, b, a } = parseColor(value);
  return `0x${hex2(r)}${hex2(g)}${hex2(b)}${hex2(alpha255(a))}`;
}

/** 0xAARRGGBB, as Compose's `Color(Long)` takes it. */
export function argbHex(value) {
  const { r, g, b, a } = parseColor(value);
  return `0x${hex2(alpha255(a))}${hex2(r)}${hex2(g)}${hex2(b)}`;
}

function sortedEntries(group, numeric) {
  const entries = Object.entries(group);
  if (numeric) entries.sort((x, y) => Number(x[0]) - Number(y[0]));
  return entries;
}

/**
 * The parts both emitters need, from resolved trees.
 * `light` is the resolved base tree; `dark` the base with the dark overrides on top.
 * `descriptions` maps `color.semantic.<key>` to its description, if any.
 */
export function nativeModel({ light, dark, descriptions = {} }) {
  const semantic = Object.keys(light.color.semantic).map((key) => ({
    key,
    light: light.color.semantic[key],
    dark: dark.color.semantic[key],
    description: descriptions[key],
  }));
  return {
    semantic,
    brand: sortedEntries(light.color.brand, true),
    spacing: sortedEntries(light.spacing, true).map(([k, v]) => [k, px(v)]),
    radius: Object.entries(light.radius).map(([k, v]) => [k, px(v)]),
    typeSize: Object.entries(light.type.size).map(([k, v]) => [k, px(v)]),
    fonts: [
      ["heading", firstFamily(light.type.display.family)],
      ["body", firstFamily(light.type.body.family)],
    ],
  };
}

// ---------------------------------------------------------------------------
// Swift
// ---------------------------------------------------------------------------

export function emitSwift(model) {
  const L = [];
  for (const h of HEADER) L.push(`// ${h}`);
  L.push(
    "",
    "import SwiftUI",
    "#if canImport(UIKit)",
    "import UIKit",
    "#elseif canImport(AppKit)",
    "import AppKit",
    "#endif",
    "",
    "/// Ink & Brass: Maktaba's design tokens, the same values as the web's.",
    "public enum MaktabaTokens {",
    "    /// A colour's light and dark values, each 0xRRGGBBAA.",
    "    public struct ColorPair: Sendable, Hashable {",
    "        public let light: UInt32",
    "        public let dark: UInt32",
    "",
    "        /// A SwiftUI colour that follows the light or dark appearance.",
    "        public var color: Color { Color(tokenLight: light, dark: dark) }",
    "    }",
    "",
    "    /// The semantic colours (`color.semantic.*`).",
    "    public enum Colors {"
  );
  model.semantic.forEach((c, i) => {
    if (i > 0) L.push("");
    if (c.description) L.push(`        /// ${c.description}`);
    L.push(
      `        public static let ${identifier(c.key)} = ColorPair(light: ${rgbaHex(c.light)}, dark: ${rgbaHex(c.dark)})`
    );
  });
  L.push(
    "    }",
    "",
    "    /// The brass palette (`color.brand.*`), each 0xRRGGBBAA.",
    "    public enum Brand {"
  );
  for (const [k, v] of model.brand) {
    L.push(`        public static let ${identifier(k, "brand")}: UInt32 = ${rgbaHex(v)}`);
  }
  const cgGroup = (doc, name, entries, prefix) => {
    L.push("    }", "", `    /// ${doc}`, `    public enum ${name} {`);
    for (const [k, v] of entries) {
      L.push(`        public static let ${identifier(k, prefix)}: CGFloat = ${v}`);
    }
  };
  cgGroup("Spacing in points (`spacing.*`).", "Spacing", model.spacing, "s");
  cgGroup("Corner radii in points (`radius.*`).", "Radius", model.radius, "r");
  cgGroup("Type sizes in points (`type.size.*`).", "TypeSize", model.typeSize, "t");
  L.push("    }", "", "    /// The font families the apps bundle.", "    public enum Fonts {");
  for (const [k, v] of model.fonts) {
    L.push(`        public static let ${k} = ${JSON.stringify(v)}`);
  }
  L.push(
    "    }",
    "}",
    "",
    "private extension Color {",
    "    init(tokenLight light: UInt32, dark: UInt32) {",
    "        #if canImport(UIKit)",
    "        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(tokenRGBA: dark) : UIColor(tokenRGBA: light) })",
    "        #elseif canImport(AppKit)",
    "        self.init(nsColor: NSColor(name: nil) { appearance in",
    "            appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? NSColor(tokenRGBA: dark) : NSColor(tokenRGBA: light)",
    "        })",
    "        #endif",
    "    }",
    "}",
    "",
    "#if canImport(UIKit)",
    "private extension UIColor {",
    "    convenience init(tokenRGBA v: UInt32) {",
    "        self.init(red: CGFloat(v >> 24 & 0xFF) / 255, green: CGFloat(v >> 16 & 0xFF) / 255,",
    "                  blue: CGFloat(v >> 8 & 0xFF) / 255, alpha: CGFloat(v & 0xFF) / 255)",
    "    }",
    "}",
    "#elseif canImport(AppKit)",
    "private extension NSColor {",
    "    convenience init(tokenRGBA v: UInt32) {",
    "        self.init(srgbRed: CGFloat(v >> 24 & 0xFF) / 255, green: CGFloat(v >> 16 & 0xFF) / 255,",
    "                  blue: CGFloat(v >> 8 & 0xFF) / 255, alpha: CGFloat(v & 0xFF) / 255)",
    "    }",
    "}",
    "#endif",
    ""
  );
  return L.join("\n");
}

