export function emitKotlin(model) {
  const L = [];
  for (const h of HEADER) L.push(`// ${h}`);
  L.push(
    "",
    "package com.hamzalabs.maktaba.core.ui",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "",
    "/** Ink & Brass: Maktaba's design tokens, the same values as the web's. */",
    "object MaktabaTokens {"
  );
  for (const [theme, doc] of [
    ["light", "The semantic colours in the light theme (`color.semantic.*`)."],
    ["dark", "The semantic colours in the dark theme (`tokens.dark.json`)."],
  ]) {
    L.push(`    /** ${doc} */`, `    object ${theme === "light" ? "Light" : "Dark"} {`);
    for (const c of model.semantic) {
      if (c.description) L.push(`        /** ${c.description} */`);
      L.push(`        val ${identifier(c.key)} = Color(${argbHex(c[theme])})`);
    }
    L.push("    }", "");
  }
  L.push("    /** The brass palette (`color.brand.*`). */", "    object Brand {");
  for (const [k, v] of model.brand) {
    L.push(`        val ${identifier(k, "brand")} = Color(${argbHex(v)})`);
  }
  const group = (doc, name, entries, prefix, unit) => {
    L.push("    }", "", `    /** ${doc} */`, `    object ${name} {`);
    for (const [k, v] of entries) L.push(`        val ${identifier(k, prefix)} = ${v}.${unit}`);
  };
  group("Spacing (`spacing.*`).", "Spacing", model.spacing, "s", "dp");
  group("Corner radii (`radius.*`).", "Radius", model.radius, "r", "dp");
  group("Type sizes (`type.size.*`).", "TypeSize", model.typeSize, "t", "sp");
  L.push("    }", "", "    /** The font families the apps bundle. */", "    object Fonts {");
  for (const [k, v] of model.fonts) {
    L.push(`        const val ${k.toUpperCase()} = ${JSON.stringify(v)}`);
  }
  L.push("    }", "}", "");
  return L.join("\n");
}
