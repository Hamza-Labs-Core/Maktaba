var updateTexts = flag.Bool("update", false, "rewrite setup_texts_web.go from web/src/i18n")

// webTextsFile holds the app's texts the terminal shows (webSetupTexts).
const webTextsFile = "setup_texts_web.go"

// The terminal says what the desktop says: the app's texts it shows are
// webSetupTexts, made from web/src/i18n (every coded text, and every setup. or
// login. key this package's code names), so a new code or a changed word in the
// app only needs `go test -run TestSetupTextsMatchTheApp -update`.
func TestSetupTextsMatchTheApp(t *testing.T) {
	web := map[string]map[string]string{}
	for _, lang := range setupLangs {
		b, err := os.ReadFile(filepath.Join("..", "..", "web", "src", "i18n", lang+".json"))
		if err != nil {
			t.Fatal(err)
		}
		m := map[string]string{}
		if err := json.Unmarshal(b, &m); err != nil {
			t.Fatal(err)
		}
		web[lang] = m
	}
	used, err := keysTheCodeNames()
	if err != nil {
		t.Fatal(err)
	}
	var keys []string
	for key := range web["en"] {
		coded := strings.HasPrefix(key, "setup.check.note.") || strings.HasPrefix(key, "setup.check.run.") ||
			strings.HasPrefix(key, "setup.error.")
		if coded || used[key] {
			keys = append(keys, key)
		}
	}
	for key := range used {
		_, app := web["en"][key]
		_, own := terminalTexts[key]
		switch {
		case strings.HasPrefix(key, "terminal."):
			if !own {
				t.Errorf("the code says %s, which terminalTexts lacks", key)
			}
		case !app:
			t.Errorf("the code says %s, which is not the app's (web/src/i18n/en.json): use a terminal. key", key)
		}
	}
	slices.Sort(keys)
	want, err := renderWebTexts(web, keys)
	if err != nil {
		t.Fatal(err)
	}
	if *updateTexts {
		if err := os.WriteFile(webTextsFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(webTextsFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
		t.Errorf("%s is not the app's texts (web/src/i18n): run go test -run TestSetupTextsMatchTheApp -update in cmd/maktaba-server", webTextsFile)
	}
	for key, v := range terminalTexts {
		if !strings.HasPrefix(key, "terminal.") {
			t.Errorf("%s: the terminal's own keys start with terminal.", key)
		}
		if v[0] == "" || v[1] == "" {
			t.Errorf("%s lacks a language", key)
		}
	}
}

// keysTheCodeNames are the text keys this package's code shows: the literal
// first argument of every get and say call (texts.get, appSetup.say), the
// generated file aside.
func keysTheCodeNames() (map[string]bool, error) {
	files, err := filepath.Glob("*.go")
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	keys := map[string]bool{}
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") || f == webTextsFile {
			continue
		}
		file, err := parser.ParseFile(fset, f, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		ast.Inspect(file, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) == 0 {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || (sel.Sel.Name != "get" && sel.Sel.Name != "say") {
				return true
			}
			lit, ok := call.Args[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			// a key, not another command's line (setup --node prints with its own say)
			s, err := strconv.Unquote(lit.Value)
			if err == nil && !strings.ContainsAny(s, " %") && (strings.HasPrefix(s, "setup.") ||
				strings.HasPrefix(s, "login.") || strings.HasPrefix(s, "terminal.")) {
				keys[s] = true
			}
			return true
		})
	}
	return keys, nil
}

// renderWebTexts is setup_texts_web.go for keys, gofmt'ed.
func renderWebTexts(web map[string]map[string]string, keys []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go test -run TestSetupTextsMatchTheApp -update; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("// webSetupTexts are the desktop app's words (web/src/i18n/{en,ar}.json) that the\n")
	b.WriteString("// terminal setup shows, key → {en, ar}: every coded text (setup.check.note.<code>,\n")
	b.WriteString("// setup.check.run.<role>, setup.error.<code>) and the keys its code names.\n")
	b.WriteString("var webSetupTexts = map[string][2]string{\n")
	for _, k := range keys {
		ar, ok := web["ar"][k]
		if !ok {
			return nil, fmt.Errorf("%s has no Arabic in web/src/i18n/ar.json", k)
		}
		fmt.Fprintf(&b, "\t%s: {%s, %s},\n", strconv.Quote(k), strconv.Quote(web["en"][k]), strconv.Quote(ar))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func TestSetupLang(t *testing.T) {
	env := func(m map[string]string) func(string) string { return func(k string) string { return m[k] } }
	for _, c := range []struct {
		flag string
		env  map[string]string
		want string
	}{
		{"", nil, "en"},
		{"", map[string]string{"LANG": "ar_SA.UTF-8"}, "ar"},
		{"", map[string]string{"LANG": "ar_SA.UTF-8", "LC_ALL": "en_US.UTF-8"}, "en"},
		{"", map[string]string{"LC_MESSAGES": "ar_EG"}, "ar"},
		{"ar", map[string]string{"LANG": "en_GB.UTF-8"}, "ar"},
		{"en", map[string]string{"LANG": "ar"}, "en"},
	} {
		if got, err := setupLang(c.flag, env(c.env)); err != nil || got != c.want {
			t.Errorf("%q %v: %q %v", c.flag, c.env, got, err)
		}
	}
	if _, err := setupLang("de", env(nil)); err == nil {
		t.Error("an unknown language was taken")
	}
	if got := textsFor("en").get("terminal.done", "url", "http://x"); got != "Maktaba is set up. Open http://x (or this computer's address on your network)." {
		t.Errorf("placeholders: %q", got)
	}
}
