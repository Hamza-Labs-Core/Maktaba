#!/usr/bin/env python3
"""Copies the shared redaction list (shared/redact/rules.json, Epic 53 story 53.01)
into every logger that embeds it at build time; --check fails, naming the copy, when
one is not current (the repo job runs it on every pull request).

Go, Python and the web read a JSON copy (keep rules.json as the web's prettier writes it:
the web's copy is checked by prettier too); Swift and Kotlin a source file holding the
same text as a raw string; the desktop shell (Rust) includes the original itself.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RULES = ROOT / "shared/redact/rules.json"

JSON_COPIES = [
    "shared/log/go/redact_rules.json",
    "pipeline/src/maktaba_pipeline/log/redact_rules.json",
    "web/src/lib/redactRules.json",
]
SWIFT = "apps/apple/MaktabaKit/Sources/MaktabaKit/RedactRules.swift"
KOTLIN = "apps/android/core/src/main/kotlin/com/hamzalabs/maktaba/core/diagnostics/RedactRules.kt"

HEADER = "Generated by tools/log-schema/sync.py from shared/redact/rules.json: do not edit."


def swift(text: str) -> str:
    if '"""#' in text:
        raise SystemExit("rules.json holds a Swift raw-string terminator")
    return (
        f"// {HEADER}\n\n"
        "/// The shared redaction list (Epic 53 story 53.01), the same rules every Maktaba logger uses.\n"
        # the newline before a closing delimiter is not part of a Swift string: one more keeps
        # the text's own last newline
        f'let redactRulesJSON = #"""\n{text}\n"""#\n'
    )


def kotlin(text: str) -> str:
    if '"""' in text or "${" in text:
        raise SystemExit("rules.json holds text a Kotlin raw string cannot carry")
    return (
        f"// {HEADER}\n"
        "package com.hamzalabs.maktaba.core.diagnostics\n\n"
        "/** The shared redaction list (Epic 53 story 53.01), the same rules every Maktaba logger uses. */\n"
        f'internal const val REDACT_RULES_JSON = """{text}"""\n'
    )


def wanted() -> dict[str, str]:
    text = RULES.read_text(encoding="utf-8")
    out = {p: text for p in JSON_COPIES}
    out[SWIFT] = swift(text)
    out[KOTLIN] = kotlin(text)
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for rel, body in wanted().items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == body:
            continue
        if check:
            stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding="utf-8")
            print(f"wrote {rel}")
    for rel in stale:
        print(f"::error file={rel}::{rel} is not shared/redact/rules.json's current copy: run python3 tools/log-schema/sync.py")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
