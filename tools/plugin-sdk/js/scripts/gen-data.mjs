// Writes src/data.generated.ts from shared/plugins (the one source); --check fails when
// the committed file is stale (Epic 54, story 54.01 §3).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const shared = join(here, "..", "..", "..", "..", "shared", "plugins");
const out = join(here, "..", "src", "data.generated.ts");
const files = {
  manifestSchema: "manifest.schema.json",
  capabilitiesToml: "capabilities.toml",
  eventsToml: "events.toml",
  flowSchema: "flow.schema.json",
  flowMessages: "flow-messages.json",
};
let text = "// Generated by scripts/gen-data.mjs from shared/plugins. Do not edit.\n\n";
for (const [name, file] of Object.entries(files)) {
  text += `export const ${name} = ${JSON.stringify(readFileSync(join(shared, file), "utf8"))};\n\n`;
}
text = text.trimEnd() + "\n";
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== text) {
    console.error("src/data.generated.ts is stale: run `pnpm gen` in tools/plugin-sdk/js");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
